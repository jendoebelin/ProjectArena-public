"""Writes app/src/servers_default.h (not in git) from servers.local.cfg (not in git) or the environment, so builds made
for players have the community server filled in while the public repository holds no server addresses.

servers.local.cfg (repo root), KEY=VALUE lines:
  PROJECTARENA_SERVER=host:port          community relay (online play and bug reports); empty = players type one
  PROJECTARENA_SPARC_SERVER=host:port    EXPERIMENTAL cross-play: the Sparc server the test connects to
Environment variables of the same names override the file.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = ('PROJECTARENA_SERVER', 'PROJECTARENA_SPARC_SERVER')


def main():
    vals = {k: '' for k in KEYS}
    cfg = os.path.join(ROOT, 'servers.local.cfg')
    if os.path.exists(cfg):
        for line in open(cfg, encoding='utf-8'):
            k, _, v = line.strip().partition('=')
            if k in vals:
                vals[k] = v.strip()
    for k in KEYS:
        if os.environ.get(k):
            vals[k] = os.environ[k]
    clean = {k: ''.join(c for c in v if c.isalnum() or c in '.-:_[]') for k, v in vals.items()}
    text = ('// Generated by tools/write_servers_header.py from servers.local.cfg -- not in git.\n'
            '#pragma once\n#define PA_DEFAULT_SERVER "%s"\n#define PA_SPARC_SERVER "%s"\n'
            % (clean['PROJECTARENA_SERVER'], clean['PROJECTARENA_SPARC_SERVER']))
    path = os.path.join(ROOT, 'app', 'src', 'servers_default.h')
    if not os.path.exists(path) or open(path).read() != text:
        open(path, 'w', newline='\n').write(text)
    print('servers: community %s, sparc %s' % (clean['PROJECTARENA_SERVER'] or '(none)', clean['PROJECTARENA_SPARC_SERVER'] or '(none)'))


if __name__ == '__main__':
    main()
