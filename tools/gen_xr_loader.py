"""Generate app/src/pc/xr_funcs.inc: forwarders for the OpenXR functions the game calls, for the small built-in
loader on Windows (app/src/pc/xr_loader.cpp). Prototypes are copied from the Khronos openxr.h.

    python -I tools/gen_xr_loader.py third_party/openxr_aar/prefab/modules/headers/include/openxr/openxr.h
"""
import re
import sys

FUNCS = """xrAcquireSwapchainImage xrApplyHapticFeedback xrAttachSessionActionSets xrBeginFrame xrBeginSession
xrCreateAction xrCreateActionSet xrCreateActionSpace xrCreateInstance xrCreateReferenceSpace xrCreateSession
xrCreateSwapchain xrDestroyInstance xrDestroySession xrDestroySpace xrDestroySwapchain xrEndFrame xrEndSession
xrEnumerateInstanceExtensionProperties xrEnumerateReferenceSpaces xrEnumerateSwapchainFormats
xrEnumerateSwapchainImages xrEnumerateViewConfigurationViews xrGetActionStateBoolean xrGetActionStateFloat
xrGetActionStateVector2f xrGetInstanceProperties xrGetSystem xrGetSystemProperties xrLocateSpace xrLocateViews
xrPollEvent xrReleaseSwapchainImage xrRequestExitSession xrStringToPath xrSuggestInteractionProfileBindings
xrSyncActions xrWaitFrame xrWaitSwapchainImage""".split()


def main():
    src = open(sys.argv[1], encoding='utf-8').read()
    out = ['// Generated by tools/gen_xr_loader.py from the Khronos openxr.h -- do not edit.', '']
    for name in FUNCS:
        m = re.search(r'XRAPI_ATTR XrResult XRAPI_CALL %s\((.*?)\);' % name, src, re.S)
        if not m:
            sys.exit('prototype not found: ' + name)
        params = ' '.join(m.group(1).split())
        args = [re.sub(r'\[.*\]', '', p).split()[-1].lstrip('*') for p in params.split(',')]
        out.append('XRAPI_ATTR XrResult XRAPI_CALL %s(%s) {' % (name, params))
        out.append('    static PFN_%s f = nullptr;' % name)
        out.append('    if (!f) xrLoaderGet("%s", (PFN_xrVoidFunction*)&f);' % name)
        if name == 'xrCreateInstance':
            out.append('    XrResult r = f ? f(%s) : XR_ERROR_RUNTIME_UNAVAILABLE;' % ', '.join(args))
            out.append('    if (XR_SUCCEEDED(r)) xrLoaderSetInstance(*instance);')
            out.append('    return r;')
        else:
            out.append('    return f ? f(%s) : XR_ERROR_FUNCTION_UNSUPPORTED;' % ', '.join(args))
        out.append('}')
        out.append('')
    open('app/src/pc/xr_funcs.inc', 'w', newline='\n').write('\n'.join(out))
    print('wrote app/src/pc/xr_funcs.inc (%d functions)' % len(FUNCS))


if __name__ == '__main__':
    main()
